#include <iostream>

int main() {
    std::cout << "Hello, World!" << std::endl;
    
    // Variables and basic types
    int age = 25;
    double height = 5.9;
    std::string name = "Alice";
    
    // Output variables
    std::cout << "Name: " << name << std::endl;
    std::cout << "Age: " << age << std::endl;
    std::cout << "Height: " << height << std::endl;
    
    // Simple arithmetic
    int sum = 10 + 5;
    std::cout << "10 + 5 = " << sum << std::endl;
    
    return 0;
}